def format_summary_table(results: list) -> str:
    lines = []
    lines.append("=" * 115)
    header = f"{'Config Label':<28} | {'Median RPS':<12} | {'p50 (ms)':<16} | {'p95 (ms)':<16} | {'p99 (ms)':<16} | {'Statuses':<22}"
    lines.append(header)
    lines.append("-" * 115)
    for r in results:
        rps_str = f"{r['median_rps']:.1f} ({r['min_rps']:.1f}-{r['max_rps']:.1f})"
        p50_str = f"{r['median_p50']:.1f} ({r['min_p50']:.1f}-{r['max_p50']:.1f})"
        p95_str = f"{r['median_p95']:.1f} ({r['min_p95']:.1f}-{r['max_p95']:.1f})"
        p99_str = f"{r['median_p99']:.1f} ({r['min_p99']:.1f}-{r['max_p99']:.1f})"
        status_str = str(r['combined_statuses'])
        lines.append(f"{r['label']:<28} | {rps_str:<12} | {p50_str:<16} | {p95_str:<16} | {p99_str:<16} | {status_str:<22}")
    lines.append("=" * 115)
    return "\n".join(lines)

def parse_cpu_csv(csv_content: str):
    lines = [l.strip() for l in csv_content.strip().splitlines() if l.strip() and not l.startswith("Time")]
    srv_deltas = []
    cli_deltas = []
    prev_s = None
    prev_c = None
    for line in lines:
        parts = line.split(",")
        if len(parts) >= 3:
            try:
                s = float(parts[1])
                c = float(parts[2])
                if prev_s is not None and prev_c is not None:
                    # CPU time delta over 2s interval
                    # % CPU = (delta_seconds / 2.0s) * 100
                    s_pct = max(0.0, (s - prev_s) / 2.0 * 100.0)
                    c_pct = max(0.0, (c - prev_c) / 2.0 * 100.0)
                    srv_deltas.append(s_pct)
                    cli_deltas.append(c_pct)
                prev_s = s
                prev_c = c
            except Exception:
                pass
    s_med = statistics.median(srv_deltas) if srv_deltas else 0.0
    s_max = max(srv_deltas) if srv_deltas else 0.0
    c_med = statistics.median(cli_deltas) if cli_deltas else 0.0
    c_max = max(cli_deltas) if cli_deltas else 0.0
    return {"srv_med": s_med, "srv_max": s_max, "cli_med": c_med, "cli_max": c_max, "raw_samples": len(srv_deltas)}

